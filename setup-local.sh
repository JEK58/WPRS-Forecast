#!/usr/bin/env bash
# Local setup automation for WPRS-Forecast.
# Idempotent: safe to re-run. Never overwrites an existing .env.
#
# Usage:
#   ./setup-local.sh [--skip-install] [--skip-db] [--skip-push]
#
set -euo pipefail

SKIP_INSTALL=false
SKIP_DB=false
SKIP_PUSH=false
for arg in "$@"; do
  case "$arg" in
    --skip-install) SKIP_INSTALL=true ;;
    --skip-db) SKIP_DB=true ;;
    --skip-push) SKIP_PUSH=true ;;
    -h|--help)
      echo "Usage: ./setup-local.sh [--skip-install] [--skip-db] [--skip-push]"
      exit 0
      ;;
    *) echo "Unknown arg: $arg (see --help)"; exit 1 ;;
  esac
done

cd "$(dirname "$0")"

info()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn()  { printf '\033[1;33m!!\033[0m %s\n' "$*"; }
fail()  { printf '\033[1;31mXX\033[0m %s\n' "$*" >&2; exit 1; }

# --- 1. Prerequisite checks -------------------------------------------------
info "Checking prerequisites..."

node --version >/dev/null 2>&1 || fail "Node.js not found. Install Node >= 18.17 (https://nodejs.org)."
NODE_MAJOR=$(node -p "process.versions.node.split('.')[0]")
[ "$NODE_MAJOR" -ge 18 ] || fail "Node >= 18.17 required, found $(node --version)."

command -v pnpm >/dev/null 2>&1 || fail "pnpm not found. Install with: corepack enable pnpm  (pinned: pnpm@10.34.5)"
command -v docker >/dev/null 2>&1 || fail "Docker not found. Install Docker Desktop (https://docs.docker.com/get-docker/)."
command -v bun >/dev/null 2>&1 && HAS_BUN=true || { HAS_BUN=false; warn "bun not found — optional, only needed for 'pnpm test' and 'pnpm db:import:competitions'. Install from https://bun.sh."; }
docker info >/dev/null 2>&1 || fail "Docker daemon is not running. Start Docker Desktop first."

info "OK: $(node --version), pnpm $(pnpm --version), $(docker --version)"

# --- 2. Install dependencies -------------------------------------------------
if [ "$SKIP_INSTALL" = true ]; then
  info "Skipping pnpm install (--skip-install)."
else
  info "Installing dependencies (pnpm install)..."
  pnpm install
fi

# --- 3. Create .env with dummy defaults --------------------------------------
gen_key() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 16
  else
    # fallback: pseudo-random via node
    node -e "console.log(require('crypto').randomBytes(16).toString('hex'))"
  fi
}

if [ -f .env ]; then
  info ".env already exists — leaving it untouched."
else
  info "Creating .env with local dummy defaults..."
  API_KEY_VAL="dev-$(gen_key)"
  if command -v openssl >/dev/null 2>&1; then
    DB_PASSWORD_VAL=$(openssl rand -base64 12 | tr '+/' '-_')
  else
    DB_PASSWORD_VAL=$(node -e "console.log(require('crypto').randomBytes(9).toString('base64url'))")
  fi
  cat > .env <<EOF
# Generated by setup-local.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Dummy keys boot the app locally. See SETUP.md for where to get real keys.

# Database (random password so start-database.sh won't prompt interactively)
DATABASE_URL=postgresql://postgres:${DB_PASSWORD_VAL}@localhost:5432/wprs-forecast
POSTGRES_PASSWORD=${DB_PASSWORD_VAL}

# Redis (optional — app runs without it, caching just disabled)
REDIS_URL=redis://localhost:6379

# Internal cron protection (?apiKey=...). Self-chosen, any random string works.
API_KEY=${API_KEY_VAL}

# Partner keys for /api/worldranking. Dummy is fine unless testing those integrations.
AIRTRIBUNE_API_KEY=dev-airtribune-key
PILOT_UNION_API_KEY=dev-pilot-union-key

# External services. Dummy boots the app; features degrade gracefully (see SETUP.md).
OPENAI_API_KEY=dummy-openai-key
ALGOLIA_APP_ID=dummy-algolia-app-id
ALGOLIA_API_KEY=dummy-algolia-api-key

# Prod-only, leave empty locally
SENTRY_IGNORE_API_RESOLUTION_ERROR=1
NEXT_PUBLIC_PLAUSIBLE_SRC=
CLOUDFLARE_ACCESS_KEY_ID=
CLOUDFLARE_SECRET_ACCESS_KEY=
CLOUDFLARE_R2_ENDPOINT=
EOF
  info ".env created. Internal API_KEY=${API_KEY_VAL}"
fi

# Load .env for the steps below (allexport)
set -a
# shellcheck disable=SC1091
. ./.env
set +a

# --- 4. Start Postgres + Redis -----------------------------------------------
if [ "$SKIP_DB" = true ]; then
  info "Skipping database startup (--skip-db)."
else
  info "Starting Postgres..."
  if [ -x ./start-database.sh ]; then
    ./start-database.sh || warn "start-database.sh reported an issue — check output above."
  else
    warn "start-database.sh not executable, running: chmod +x + retry"
    chmod +x ./start-database.sh || true
    ./start-database.sh || warn "start-database.sh reported an issue — check output above."
  fi

  info "Starting Redis (docker-compose-dev.yml)..."
  if docker compose -f docker-compose-dev.yml up -d 2>/dev/null; then
    info "Redis started."
  elif docker-compose -f docker-compose-dev.yml up -d 2>/dev/null; then
    info "Redis started (via docker-compose v1)."
  else
    warn "Could not start Redis via compose. App works without Redis (REDIS_URL unset) — continuing."
  fi

  info "Waiting for Postgres to accept connections..."
  READY=false
  for i in $(seq 1 30); do
    if docker exec wprs-forecast-postgres pg_isready -U postgres >/dev/null 2>&1; then
      READY=true
      break
    fi
    sleep 1
  done
  [ "$READY" = true ] || warn "Postgres did not report ready after 30s — 'pnpm db:push' may fail; start Docker and re-run."
fi

# --- 5. Push DB schema ---------------------------------------------------------
if [ "$SKIP_PUSH" = true ]; then
  info "Skipping schema push (--skip-push)."
else
  info "Pushing DB schema (pnpm db:push)..."
  pnpm db:push
fi

# --- Done ----------------------------------------------------------------------
cat <<'NEXT'

Setup complete!

  pnpm dev        # start dev server -> http://localhost:3000
  pnpm db:studio  # inspect the database
  pnpm lint       # eslint
  bun test --watch  # tests (requires bun)

Dummy API keys are in .env and boot the app. To enable real
AI date parsing / Algolia pilot search, add real keys — see SETUP.md
("Where do the API keys come from?").

NEXT
